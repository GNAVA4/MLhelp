export const TOPIC_MAP_V = TOPIC_MAPS.length;
const MARK = '~v';
const step = (k, from) => { for (let v = from; v < TOPIC_MAP_V; v++) k = TOPIC_MAPS[v][k] || k; return k; };
const remap = (o, from) => { const out = {}; for (const [k, v] of Object.entries(o || {})) out[step(k, from)] = v; return out; };

// Переводит разделы, которые есть в объекте (локальное состояние целиком или пришедшие из облака разделы).
export function migrateTopicIds(s) {
  if (!s || typeof s !== 'object') return s;
  const out = { ...s };
  if (s.topics) {
    const { [MARK]: mark, ...rest } = s.topics, from = mark?.v || 0;
    if (from < TOPIC_MAP_V) out.topics = { ...remap(rest, from), [MARK]: { v: TOPIC_MAP_V } };
  }
  if (s.settings && (s.settings.topicMapV || 0) < TOPIC_MAP_V) out.settings = { ...s.settings, reviewOff: remap(s.settings.reviewOff, s.settings.topicMapV || 0), topicMapV: TOPIC_MAP_V };
  if (s.meta && (s.meta.topicMapV || 0) < TOPIC_MAP_V) out.meta = { ...s.meta, lastTopicId: s.meta.lastTopicId && step(s.meta.lastTopicId, s.meta.topicMapV || 0), topicMapV: TOPIC_MAP_V };
  return out;
}

// Сохранённые фильтры тем и раскрытые блоки ссылаются на старые номера блоков — сбрасываем при каждой новой версии.
export function resetStaleUiKeys() {
  try {
    if (Number(localStorage.getItem('mlc:topicMapV') || 0) >= TOPIC_MAP_V) return;
    for (const k of ['mlc:reviewScope', 'mlc:newScope', 'mlc:trainScope', 'mlc:openBlocks']) localStorage.removeItem(k);
    localStorage.setItem('mlc:topicMapV', String(TOPIC_MAP_V));
  } catch { /* приватный режим — не критично */ }
}
